-- Supabase Schema for Aviator Landing Page
-- Run this in your Supabase SQL Editor: https://supabase.com/dashboard/project/_/sql

-- 1. Claims Table
CREATE TABLE IF NOT EXISTS public.claims (
  id TEXT PRIMARY KEY,
  name TEXT,
  phone TEXT,
  email TEXT,
  promo_code TEXT DEFAULT 'AVIATOR500',
  bonus_percentage NUMERIC DEFAULT 500,
  amount NUMERIC DEFAULT 50000,
  currency TEXT DEFAULT 'INR',
  session_token TEXT,
  status TEXT DEFAULT 'APPROVED',
  timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 2. Sessions Table (Flight history)
CREATE TABLE IF NOT EXISTS public.sessions (
  id TEXT PRIMARY KEY,
  session_token TEXT,
  attempt_number INT,
  duration NUMERIC,
  multiplier NUMERIC,
  outcome TEXT,
  bet_amount NUMERIC,
  currency TEXT DEFAULT 'INR',
  timestamp TIMESTAMPTZ DEFAULT timezone('utc'::text, now()),
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 3. Live Winners Feed Table
CREATE TABLE IF NOT EXISTS public.winners (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  avatar TEXT DEFAULT 'star',
  multiplier NUMERIC NOT NULL,
  amount NUMERIC NOT NULL,
  currency TEXT DEFAULT 'INR',
  time TEXT DEFAULT 'Just now',
  created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

-- 4. Platform Stats Table
CREATE TABLE IF NOT EXISTS public.stats (
  id INT PRIMARY KEY DEFAULT 1,
  total_flights BIGINT DEFAULT 142857,
  total_bonus_claimed BIGINT DEFAULT 41304886,
  active_players INT DEFAULT 194,
  updated_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
);

