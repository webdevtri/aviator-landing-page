-- Enable Row Level Security (RLS)
ALTER TABLE public.claims ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.winners ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.stats ENABLE ROW LEVEL SECURITY;

-- Allow anonymous read/write access (for public landing page endpoints)
CREATE POLICY "Allow public read on claims" ON public.claims FOR SELECT USING (true);
CREATE POLICY "Allow public insert on claims" ON public.claims FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read on sessions" ON public.sessions FOR SELECT USING (true);
CREATE POLICY "Allow public insert on sessions" ON public.sessions FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read on winners" ON public.winners FOR SELECT USING (true);
CREATE POLICY "Allow public insert on winners" ON public.winners FOR INSERT WITH CHECK (true);

CREATE POLICY "Allow public read on stats" ON public.stats FOR SELECT USING (true);
CREATE POLICY "Allow public update on stats" ON public.stats FOR ALL USING (true);
